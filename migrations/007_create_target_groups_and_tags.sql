CREATE TABLE IF NOT EXISTS target_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_target_groups_name_lower
ON target_groups (LOWER(name));

CREATE TABLE IF NOT EXISTS target_group_assignments (
    probe_id VARCHAR(100) NOT NULL,
    target TEXT NOT NULL,
    group_id BIGINT NOT NULL REFERENCES target_groups(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (probe_id, target)
);

CREATE INDEX IF NOT EXISTS idx_target_group_assignments_group_id
ON target_group_assignments (group_id);

CREATE TABLE IF NOT EXISTS target_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_target_tags_name_lower
ON target_tags (LOWER(name));

CREATE TABLE IF NOT EXISTS target_tag_assignments (
    probe_id VARCHAR(100) NOT NULL,
    target TEXT NOT NULL,
    tag_id BIGINT NOT NULL REFERENCES target_tags(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (probe_id, target, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_target_tag_assignments_tag_id
ON target_tag_assignments (tag_id);
